import { Octokit } from 'octokit';
import { MappedCode } from './figmaToShadcnMapper.js';

/**
 * figma2ui/brain - GitHub PR auto-generation
 * Called from the Figma plugin -> opens a PR with the generated code
 */
export async function createFigmaPR(opts: {
  token: string;
  owner: string;
  repo: string;
  branch: string;
  files: { path: string, content: string }[];
  figmaFileUrl: string;
}) {
  const octokit = new Octokit({ auth: opts.token });

  // 1. Get main branch SHA
  const { data: ref } = await octokit.rest.git.getRef({
    owner: opts.owner,
    repo: opts.repo,
    ref: 'heads/main'
  });

  // 2. Create new branch
  await octokit.rest.git.createRef({
    owner: opts.owner,
    repo: opts.repo,
    ref: `refs/heads/${opts.branch}`,
    sha: ref.object.sha
  });

  // 3. Create blobs & commit (simplified: one file demo)
  // Real impl would create tree
  for (const file of opts.files) {
    await octokit.rest.repos.createOrUpdateFileContents({
      owner: opts.owner,
      repo: opts.repo,
      path: file.path,
      message: `feat(figma2ui): import from ${opts.figmaFileUrl}`,
      content: Buffer.from(file.content).toString('base64'),
      branch: opts.branch
    });
  }

  // 4. Create PR
  const { data: pr } = await octokit.rest.pulls.create({
    owner: opts.owner,
    repo: opts.repo,
    head: opts.branch,
    base: 'main',
    title: `feat: Figma import - ${opts.files.length} components`,
    body: `Auto-generated by [figma2ui](https://github.com/figma2ui)\n\nSource: ${opts.figmaFileUrl}\n\n- [x] Maps to shadcn/ui (no div soup)\n- [x] Visual diff ready`
  });

  return pr.html_url;
}